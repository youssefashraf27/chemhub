-- =========================================================
-- 2) Automatically create/sync a profile after signup
-- =========================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, phone, department, year_level, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name',''),
    new.raw_user_meta_data->>'phone',
    new.raw_user_meta_data->>'department',
    coalesce(new.raw_user_meta_data->>'year_level', new.raw_user_meta_data->>'department'),
    new.email,
    'student'
  )
  on conflict (id) do update set
    full_name = coalesce(excluded.full_name, public.profiles.full_name),
    phone = coalesce(excluded.phone, public.profiles.phone),
    department = coalesce(excluded.department, public.profiles.department),
    year_level = coalesce(excluded.year_level, public.profiles.year_level),
    email = coalesce(excluded.email, public.profiles.email),
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

