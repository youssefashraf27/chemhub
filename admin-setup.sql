insert into public.profiles (id, full_name, phone, department, year_level, email, role)
select u.id,
       u.raw_user_meta_data->>'full_name',
       u.raw_user_meta_data->>'phone',
       u.raw_user_meta_data->>'department',
       coalesce(u.raw_user_meta_data->>'year_level', u.raw_user_meta_data->>'department'),
       u.email,
       'student'
from auth.users u
on conflict (id) do update set
  email = excluded.email,
  full_name = coalesce(public.profiles.full_name, excluded.full_name),
  phone = coalesce(public.profiles.phone, excluded.phone),
  department = coalesce(public.profiles.department, excluded.department),
  year_level = coalesce(public.profiles.year_level, excluded.year_level),
  updated_at = now();

